#!/usr/bin/env node
import { createHash, createPrivateKey, createPublicKey, sign, verify } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { isMain } from './entry.mjs';
import { unzipSync } from 'fflate';
import { buildPackage } from './build.mjs';

import { parseVersion } from './version.mjs';
export { parseVersion } from './version.mjs';
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const jsonBytes = value => Buffer.from(JSON.stringify(value, null, 2) + '\n');

/** Produces data only; publication and signing belong to a separately authorized job. */
export async function buildRelease(directory, tag) {
  const result = await buildPackage(directory);
  const manifest = result.manifest;
  const channel = parseVersion(manifest.version);
  const metadata = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  if (tag !== `v${manifest.version}` || metadata.version !== manifest.version) throw new Error('Tag, package and manifest version must agree');
  // Build metadata is valid SemVer, but '+' is deliberately excluded from archive resource paths.
  const asset = `${manifest.id}-${manifest.version.replaceAll('+', '_')}.rikkaplug`;
  const index = jsonBytes({ schemaVersion: 1, packages: [{
    id: manifest.id, version: manifest.version, asset, sha256: result.sha256, sizeBytes: result.archive.length,
    apiVersion: manifest.apiVersion ?? '1', runtime: manifest.runtime ?? 'quickjs-es2020',
    requiredFeatures: manifest.requiredFeatures ?? [], capabilities: manifest.capabilities ?? [],
  }] });
  const assets = { [asset]: Buffer.from(result.archive) };
  verifyRelease(index, assets);
  return { index, assets, prerelease: channel.prerelease };
}

function requireCurve(key) {
  if (key.asymmetricKeyType !== 'ec' || key.asymmetricKeyDetails.namedCurve !== 'prime256v1') throw new Error('Expected P-256 signing key');
}
export function signIndex(index, input) {
  const key = input?.type === 'private' ? input : createPrivateKey(input);
  requireCurve(key);
  return jsonBytes({ algorithm: 'ES256', publicKey: createPublicKey(key).export({ format: 'der', type: 'spki' }).toString('base64'),
    signature: sign('sha256', index, key).toString('base64') });
}

export function verifyRelease(indexBytes, assets, signature) {
  if (indexBytes.length === 0 || indexBytes.length > 65536) throw new Error('Invalid index size');
  const index = JSON.parse(indexBytes);
  if (index.schemaVersion !== 1 || !Array.isArray(index.packages) || index.packages.length < 1 || index.packages.length > 64) throw new Error('Invalid release index');
  const ids = new Set(), names = new Set();
  for (const entry of index.packages) {
    parseVersion(entry.version);
    if (!/^[a-z][a-z0-9]*(\.[a-z][a-z0-9_-]*)+$/.test(entry.id ?? '') || entry.id.length > 120 || ids.has(entry.id)) throw new Error('Invalid plugin identity');
    if (typeof entry.asset !== 'string' || entry.asset.length > 200 || !/^[A-Za-z0-9_-][A-Za-z0-9_.-]*\.rikkaplug$/.test(entry.asset) || names.has(entry.asset.toLowerCase())) throw new Error('Invalid asset name');
    ids.add(entry.id); names.add(entry.asset.toLowerCase());
    const bytes = assets[entry.asset];
    if (!bytes || !Number.isInteger(entry.sizeBytes) || entry.sizeBytes < 22 || entry.sizeBytes > 4194304 || bytes.length !== entry.sizeBytes) throw new Error('Asset size mismatch');
    if (!/^[a-f0-9]{64}$/.test(entry.sha256 ?? '') || sha256(bytes) !== entry.sha256) throw new Error('Asset hash mismatch');
    // The immutable package is generated by buildPackage; the host additionally enforces ZIP entry and extraction limits.
    const files = unzipSync(bytes, { filter: file => {
      if (file.originalSize > 8388608) throw new Error('Expanded file size exceeds limit');
      return file.name === 'manifest.json';
    } });
    const manifest = JSON.parse(Buffer.from(files['manifest.json'] ?? []).toString('utf8'));
    for (const field of ['id', 'version', 'apiVersion', 'runtime', 'requiredFeatures', 'capabilities']) {
      const fallback = { apiVersion: '1', runtime: 'quickjs-es2020', requiredFeatures: [], capabilities: [] };
      const normalize = value => Array.isArray(value) ? [...value].sort() : value;
      if (JSON.stringify(normalize(entry[field])) !== JSON.stringify(normalize(manifest[field] ?? fallback[field]))) throw new Error(`Index disagrees with manifest: ${field}`);
    }
  }
  if (Object.keys(assets).length !== names.size) throw new Error('Unexpected package assets');
  if (signature) {
    if (signature.length > 4096) throw new Error('Invalid signature size');
    const envelope = JSON.parse(signature);
    if (envelope.algorithm !== 'ES256') throw new Error('Invalid signature algorithm');
    const key = createPublicKey({ key: Buffer.from(envelope.publicKey, 'base64'), format: 'der', type: 'spki' });
    requireCurve(key);
    if (!verify('sha256', indexBytes, key, Buffer.from(envelope.signature, 'base64'))) throw new Error('Invalid release signature');
  }
  return index;
}

async function optionalSignature(directory) {
  try { return await readFile(join(directory, 'release.json.sig')); }
  catch (error) { if (error.code !== 'ENOENT') throw error; return undefined; }
}
export async function readRelease(directory) {
  const index = await readFile(join(directory, 'release.json'));
  // Validate asset paths before touching the filesystem, including before signature verification.
  const entries = JSON.parse(index).packages;
  if (!Array.isArray(entries) || entries.some(e => typeof e.asset !== 'string' || !/^[A-Za-z0-9_-][A-Za-z0-9_.-]*\.rikkaplug$/.test(e.asset))) throw new Error('Invalid asset name');
  const assets = Object.fromEntries(await Promise.all(entries.map(async e => [e.asset, await readFile(join(directory, e.asset))])));
  const signature = await optionalSignature(directory);
  verifyRelease(index, assets, signature);
  return { index, assets, signature };
}

async function main([command, directory, argument, ...extra]) {
  if (extra.length || !directory) throw new Error('Usage: rikkaplug-release build <plugin-directory> <output-directory> | verify <directory> | sign <directory>');
  if (command === 'build') {
    if (!argument || !process.env.RIKKA_RELEASE_TAG) throw new Error('Output directory and RIKKA_RELEASE_TAG are required');
    const release = await buildRelease(directory, process.env.RIKKA_RELEASE_TAG);
    await mkdir(argument, { recursive: true });
    for (const [name, bytes] of Object.entries({ 'release.json': release.index, ...release.assets })) await writeFile(join(argument, name), bytes, { flag: 'wx' });
  } else if (command === 'sign') {
    if (argument || !process.env.RIKKA_SIGNING_KEY_FILE) throw new Error('RIKKA_SIGNING_KEY_FILE is required');
    const release = await readRelease(directory);
    const signed = signIndex(release.index, await readFile(process.env.RIKKA_SIGNING_KEY_FILE));
    await writeFile(join(directory, 'release.json.sig'), signed, { flag: 'wx' });
  } else if (command === 'verify') {
    if (argument) throw new Error('Unexpected argument');
    await readRelease(directory);
  } else throw new Error('Unknown release command');
}
if (isMain(import.meta.url)) {
  main(process.argv.slice(2)).catch(error => { console.error(error.message); process.exitCode = 1; });
}
